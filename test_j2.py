import asyncio
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path='/opt/pw-browsers/chromium-1243/chrome-linux64/chrome')
        pg = await b.new_page(viewport={'width': 400, 'height': 860}, device_scale_factor=2)
        errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.goto('http://localhost:8765/index.html'); await pg.wait_for_timeout(1200)
        await pg.evaluate("document.querySelector('.home-grid').scrollIntoView({block:'center'})"); await pg.wait_for_timeout(200)
        await pg.screenshot(path='shots/k0.png')
        print('grid order:', await pg.evaluate("[...document.querySelectorAll('.home-grid .tile b')].map(b=>b.textContent).join(' | ')"))
        await pg.evaluate("location.hash='#/view/spell-witch-bottle'"); await pg.wait_for_timeout(600)
        await pg.click('#logw'); await pg.wait_for_timeout(300)
        await pg.fill('#lw-for','Protect the new apartment'); await pg.fill('#lw-notes','Buried by the front step at dusk; used extra rosemary.')
        await pg.screenshot(path='shots/k1.png')
        await pg.click('#lw-s'); await pg.wait_for_timeout(500)
        await pg.evaluate("document.querySelector('#logw').scrollIntoView({block:'center'})"); await pg.screenshot(path='shots/k2.png')
        await pg.evaluate("location.hash='#/view/crystal-amethyst'"); await pg.wait_for_timeout(500)
        await pg.click('#logw'); await pg.wait_for_timeout(300); await pg.fill('#lw-notes','Under pillow'); await pg.click('#lw-s'); await pg.wait_for_timeout(400)
        await pg.evaluate("location.hash='#/reading/tarot-one-card-daily'"); await pg.wait_for_timeout(600)
        await pg.reload(); await pg.wait_for_timeout(1000)
        await pg.evaluate("location.hash='#/journal'"); await pg.wait_for_timeout(600)
        print('entries:', await pg.locator('#jl .row').count())
        await pg.screenshot(path='shots/k3.png')
        await pg.click('#jl .row >> nth=2'); await pg.wait_for_timeout(500)
        print('entry hash', await pg.evaluate('location.hash'))
        await pg.click('[data-o=worked]'); await pg.fill('#res','Neighbours stopped arguing; felt calm.'); await pg.wait_for_timeout(700)
        await pg.screenshot(path='shots/k4.png', full_page=True)
        await pg.evaluate("location.hash='#/journal?w=1'"); await pg.wait_for_timeout(500)
        print('awaiting after results:', await pg.locator('#jl .row').count())
        await pg.evaluate("location.hash='#/journal?t=tarot'"); await pg.wait_for_timeout(400)
        await pg.click('#jl .row'); await pg.wait_for_timeout(400)
        print('tarot results box:', await pg.locator('#res').count())
        print(errs); await b.close()
asyncio.run(main())

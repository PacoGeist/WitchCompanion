import asyncio
from playwright.async_api import async_playwright
async def main():
  async with async_playwright() as p:
    b = await p.chromium.launch(executable_path='/opt/pw-browsers/chromium-1243/chrome-linux64/chrome', args=['--use-fake-ui-for-media-stream','--use-fake-device-for-media-stream'])
    ctx = await b.new_context(viewport={'width':390,'height':844}, device_scale_factor=2, permissions=['camera'])
    pg = await ctx.new_page(); errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
    await pg.goto('http://localhost:8765/index.html'); await pg.wait_for_timeout(1500)
    await pg.evaluate("location.hash='#/credits'"); await pg.wait_for_timeout(400)
    print('about top:', await pg.evaluate("document.querySelector('#view').firstElementChild.textContent"))
    await pg.evaluate("location.hash='#/decks'"); await pg.wait_for_timeout(500)
    await pg.screenshot(path='shots/d2_list.png')
    await pg.click('#dphoto'); await pg.wait_for_timeout(400)
    await pg.screenshot(path='shots/d2_new.png')
    await pg.fill('#dn','Wild Moon Deck'); await pg.click('#dsav'); await pg.wait_for_timeout(2500)
    print('camera open:', await pg.evaluate("document.querySelector('.cam-top b')?.textContent"), await pg.evaluate("location.hash"))
    await pg.click('#cs'); await pg.wait_for_timeout(700); await pg.click('#as'); await pg.wait_for_timeout(2000)
    print('next:', await pg.evaluate("document.querySelector('.cam-top b')?.textContent"))
    await pg.click('#cx'); await pg.wait_for_timeout(700)
    await pg.click('#dcov'); await pg.wait_for_timeout(300); await pg.click('#pc'); await pg.wait_for_timeout(2000)
    print('cover cam:', await pg.evaluate("document.querySelector('.cam-top b')?.textContent"))
    await pg.click('#cs'); await pg.wait_for_timeout(700); await pg.click('#as'); await pg.wait_for_timeout(800)
    print('cover set:', await pg.evaluate("!!Decks.list[0].image"), Decks:=await pg.evaluate("Decks.list[0].cards"))
    await pg.evaluate("location.hash='#/decks'"); await pg.wait_for_timeout(500)
    await pg.click('#dphoto'); await pg.wait_for_timeout(300); await pg.click('[data-shoot]'); await pg.wait_for_timeout(2500)
    print('resume at:', await pg.evaluate("document.querySelector('.cam-top b')?.textContent"))
    await pg.click('#cx'); await pg.wait_for_timeout(500)
    await pg.screenshot(path='shots/d2_page.png')
    print('errs', errs[:3]); await b.close()
asyncio.run(main())

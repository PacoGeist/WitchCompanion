import asyncio
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path='/opt/pw-browsers/chromium-1243/chrome-linux64/chrome')
        ctx = await b.new_context(viewport={'width': 400, 'height': 860}, device_scale_factor=2, has_touch=False)
        pg = await ctx.new_page()
        errs = []
        pg.on('console', lambda m: m.type == 'error' and 'favicon' not in m.text and errs.append(m.text))
        pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.goto('http://localhost:8765/index.html#/edit/spell'); await pg.wait_for_timeout(1000)
        f = '#ef'
        await pg.fill('[data-field=name] input', 'Midnight Rosemary Ward')
        await pg.fill('[data-field=description] textarea', 'A small ward for the threshold, made under a waning moon.')
        await pg.fill('[data-field=metaphysical] input', 'protection, Banishing')
        await pg.fill('[data-field=ingredients] .it', 'Rosemary sprigs')
        await pg.fill('[data-field=ingredients] .amt', '3')
        await pg.click('[data-field=ingredients] button.btn')
        await pg.fill('[data-field=ingredients] .item:nth-child(2) .it', 'Black Tourmaline chip')
        await pg.fill('[data-field=steps] textarea', 'Bind the sprigs with red thread.')
        await pg.fill('[data-field=chant] textarea', 'Rosemary green, guard between,\nnothing ill may pass unseen.')
        await pg.click('[data-p="Waning Crescent"]')
        await pg.click('[data-a=art]'); await pg.wait_for_timeout(300); await pg.click('.gallery [data-n=broom]')
        await pg.click('#ef button[type=submit]'); await pg.wait_for_timeout(900)
        print('after save hash', await pg.evaluate('location.hash'))
        await pg.screenshot(path='shots/flow_spell.png', full_page=True)
        # sigil
        await pg.evaluate("location.hash='#/edit/sigil'"); await pg.wait_for_timeout(700)
        await pg.fill('[data-field=name] input', 'Ward of Quiet Sleep')
        box = await pg.locator('canvas').bounding_box()
        await pg.click('#sym [data-s="6"]')
        await pg.mouse.move(box['x'] + box['width'] * .5, box['y'] + box['height'] * .2); await pg.mouse.down()
        for i in range(20): await pg.mouse.move(box['x'] + box['width'] * (.5 + i * .01), box['y'] + box['height'] * (.2 + i * .012))
        await pg.mouse.up()
        await pg.click('[data-a=gen]'); await pg.wait_for_timeout(300)
        await pg.fill('#sw', 'I sleep in peace'); await pg.wait_for_timeout(200)
        await pg.screenshot(path='shots/flow_sigilgen.png')
        await pg.click('#sok'); await pg.wait_for_timeout(300)
        await pg.screenshot(path='shots/flow_sigilcanvas.png')
        await pg.fill('[data-field=intention] textarea', 'By this mark my sleep is guarded.')
        await pg.click('#ef button[type=submit]'); await pg.wait_for_timeout(900)
        await pg.screenshot(path='shots/flow_sigilview.png')
        # tarot editor
        await pg.evaluate("location.hash='#/edit/tarot'"); await pg.wait_for_timeout(700)
        await pg.fill('[data-field=name] input', 'Witch Moon Spread')
        await pg.click('#padd'); await pg.fill('#plist .item:nth-child(4) .pn', 'Hidden influence')
        await pg.click('#padd'); await pg.fill('#plist .item:nth-child(5) .pn', 'Advice')
        await pg.select_option('#preset', 'circle'); await pg.wait_for_timeout(300)
        await pg.screenshot(path='shots/flow_tarotedit.png')
        await pg.click('#ef button[type=submit]'); await pg.wait_for_timeout(900)
        await pg.click('text=Draw a Reading'); await pg.wait_for_timeout(1200)
        await pg.screenshot(path='shots/flow_tarotread.png', full_page=True)
        # search & reload persistence
        await pg.reload(); await pg.wait_for_timeout(1000)
        await pg.evaluate("location.hash='#/search?q=midnight rosemary'"); await pg.wait_for_timeout(700)
        print('search results:', await pg.locator('#sres .row').count())
        await pg.evaluate("location.hash='#/view/herb-rosemary'"); await pg.wait_for_timeout(700)
        print('rosemary used-in mentions custom:', await pg.locator('text=Midnight Rosemary Ward').count())
        await pg.screenshot(path='shots/flow_rosemary.png', full_page=True)
        # day theme
        await pg.evaluate("location.hash='#/settings'"); await pg.wait_for_timeout(500)
        await pg.click('#theme [data-t=day]'); await pg.wait_for_timeout(300)
        async with pg.expect_download() as dl:
            await pg.click('#exp')
        d = await dl.value; print('backup', d.suggested_filename)
        await pg.evaluate("location.hash='#/'"); await pg.wait_for_timeout(600)
        await pg.screenshot(path='shots/flow_day_home.png')
        await pg.evaluate("location.hash='#/view/herb-belladonna'"); await pg.wait_for_timeout(600)
        await pg.screenshot(path='shots/flow_day_bella.png')
        for e in errs: print('ERR', e)
        await b.close()
asyncio.run(main())
